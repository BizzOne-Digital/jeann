const mergedCache = new Map<string, Record<string, string>>();

function mergeLocale(locale: string): Record<string, string> {
  const cached = mergedCache.get(locale);
  if (cached) return cached;

  const map: Record<string, string> = {
    ...(NAV[locale] ?? {}),
    ...(SITE[locale] ?? {}),
  };

  mergedCache.set(locale, map);
  return map;
}

export function getStaticTranslationMap(locale: string): Record<string, string> {
  return mergeLocale(locale);
}

export function lookupStaticTranslation(source: string, locale: string): string | null {
  const map = mergeLocale(locale);
  const trimmed = source.trim();
  return map[trimmed] ?? null;
}

export function getSupportedStaticLocales(): string[] {
  return [...LOCALE_CODES];
}
